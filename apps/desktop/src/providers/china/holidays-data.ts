/**
 * 中国法定节假日安排数据（SC-011 / CN-002–004、CN-007）。
 *
 * 数据是手工维护的事实，不是推导结果：放假与补班由国务院办公厅逐年发文确定，
 * 没有可以计算的公式（这一点与农历、节气不同）。因此这里登记通知原文里的
 * 日期区间与文号，识别规则（查询、连休分组、校验）在 holidays.ts。
 *
 * 每条安排对应一次通知，`year` 是通知标题里的年份，不是日期的公历年：
 * 元旦与周末连休时可能落在上一年 12 月（2024 年安排含 2023-12-30/31），
 * 这段时间属于哪一年的安排由通知决定，不由日期年份决定。
 *
 * 登记口径：
 * - `rest` 按通知原文「X 月 X 日至 X 月 X 日放假」登记为区间；通知写
 *   「与周末连休」的（2024 元旦、端午）按实际连休区间登记，区间内的周末
 *   本来就是休息日，与放假日期在语义上没有区别——UI 要的是「哪些天在放假」；
 * - `makeup` 按通知原文「X 月 X 日上班」逐日登记（调休补班日）；
 * - `names` 指通知里的条目名，合并放假的条目写多段（2025「国庆节、中秋节」）；
 * - 通知里只是鼓励、没有规定放假的日期不登记：2024 年除夕（2 月 9 日）
 *   当年只写着「鼓励各单位…安排职工休息」，因此 2024-02-09 不在数据里；
 *   2025 年起除夕已是法定假日，2025 / 2026 的安排都包含它。
 *
 * 来源均为中国政府网发布的通知原文（`sourceUrl`），数据修订时递增 `revision`。
 * 没有登记的年份查不到任何日期，UI 安静地不显示休 / 补，不做推算（P-03）。
 */

/** 放假区间（含首尾）。日期键为 YYYY-MM-DD。 */
export interface HolidayRange {
  from: string;
  to: string;
}

/** 一次通知里的一条假期安排。 */
export interface HolidayItemData {
  /** 条目名（通知原文）：通常一条一名，合并放假时多段。 */
  names: readonly string[];
  /** 放假区间；可能跨公历年（元旦与上一年 12 月的周末连休）。 */
  rest: readonly HolidayRange[];
  /** 补班日（通知里的「上班」）。 */
  makeup: readonly string[];
}

/** 某一年度的节假日安排（CN-007：年份数据与版本）。 */
export interface HolidayArrangementData {
  /** 通知年份，也是本数据集的年份键。 */
  year: number;
  /** 本仓库内的数据修订号：只改数据不改年份时递增。 */
  revision: number;
  /** 通知文号。 */
  notice: string;
  /** 通知发布日期 YYYY-MM-DD。 */
  publishedAt: string;
  /** 通知原文地址（中国政府网），供追溯；运行期不访问网络。 */
  sourceUrl: string;
  items: readonly HolidayItemData[];
}

