/**
 * 分片生成器的同步排空（SC-024）。
 *
 * 导入链路的每个阶段都有两条入口：「分片入口」把生成器交给
 * `run-yielding.ts` 驱动，任务之间让出主线程；「同步入口」就是这里的一次排空——
 * 一个任务里算完，结果与分片入口逐条相同（等价性由各自的用例对照）。
 *
 * 排空只改变执行方式，因此所有同步入口共用这一份实现：七处手抄的循环各自漂移
 * 是这类「两条入口必须一致」的约定最容易失效的地方。
 *
 * 排空与切片的区别由调用方声明的粒度决定（非正数 = 不切片），不由「生成器有没有
 * yield 过」反推：一次排空同样会经过让出点，只是立刻恢复。
 */

/** 分片粒度取 0（或负数）= 中间不让出，即同步排空。 */
export const NO_SLICES = 0;

/** 把生成器一次跑完，返回它的结果。 */
export function drain<T>(steps: Generator<void, T, void>): T {
  let step = steps.next();
  while (!step.done) {
    step = steps.next();
  }
  return step.value;
}
